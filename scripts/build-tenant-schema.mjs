// Concatenates supabase/migrations/*.sql into a single script a white-label
// tenant pastes into their own Supabase SQL Editor to stand up the same
// schema this app expects. Generated on every build (see package.json's
// "prebuild" script) so it can never silently drift from the real
// migration history — a hand-maintained combined file would go stale the
// moment a migration is added and nobody remembers to update it.
//
// Two exclusion markers keep DYOR-only content out of the tenant script:
//   - a file whose first line is exactly "-- whitelabel:exclude-file" is
//     skipped entirely (the control-plane migration itself)
//   - any line ending in "-- whitelabel:exclude-line" is stripped (the
//     JØNK-specific demo-data seed in 0029)

import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const migrationsDir = path.join(__dirname, "..", "supabase", "migrations");
const outputPath = path.join(__dirname, "..", "public", "whitelabel", "tenant-schema.sql");

const EXCLUDE_FILE_MARKER = "-- whitelabel:exclude-file";
const EXCLUDE_LINE_MARKER = "-- whitelabel:exclude-line";

async function build() {
  const entries = await readdir(migrationsDir);
  const files = entries.filter((f) => f.endsWith(".sql")).sort();

  const parts = [
    "-- Generated by scripts/build-tenant-schema.mjs — do not edit by hand.",
    "-- Run this once, in full, in your own Supabase project's SQL Editor",
    "-- (Database > SQL Editor > New query) before submitting the DYOR",
    "-- white-label onboarding form.",
    "",
  ];

  let includedCount = 0;
  let skippedCount = 0;

  for (const file of files) {
    const raw = await readFile(path.join(migrationsDir, file), "utf8");
    const firstLine = raw.split("\n", 1)[0]?.trim();
    if (firstLine === EXCLUDE_FILE_MARKER) {
      skippedCount++;
      continue;
    }

    const cleaned = raw
      .split("\n")
      .filter((line) => !line.trimEnd().endsWith(EXCLUDE_LINE_MARKER))
      .join("\n");

    parts.push(`-- === ${file} ===`, cleaned.trimEnd(), "");
    includedCount++;
  }

  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, parts.join("\n") + "\n", "utf8");

  console.log(
    `Wrote ${outputPath} (${includedCount} migrations included, ${skippedCount} excluded)`
  );
}

build().catch((err) => {
  console.error(err);
  process.exit(1);
});
